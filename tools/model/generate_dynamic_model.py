#!/usr/bin/env python3
"""Generate the MuJoCo plant for the RB v1.3 controller simulation (model/dynamic.xml).

The plant matches the controller's 7-body model (see generate_rb_controller_geometry.py): body (with the head fused
in), then thigh / shin / wheel per side, every joint about +Y. The knee joint is the shin angle relative to the thigh;
the parallelogram makes that identical to a serial knee, so no closed loop is needed. The actuators are plain joint
torque motors: the runner converts joint torques to motor torques and applies the real motor limits, because the
knee motor also loads the hip (see sim runner).

Contact: wheel cylinders and three body boxes (shells and head) against the floor. Joint limits are the CAD hard
stops. Friction values are the ones the user supplied. Rotor inertia (armature) is an assumption.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[2]
MODEL = ROOT / "model"
OUT = ROOT / "model/dynamic.xml"

WHEEL_RADIUS = 0.035
WHEEL_HALF_WIDTH = 0.0125          # tyre spans 107.6 to 132.6 mm in y
HIP_RANGE = (math.radians(-89.85), math.radians(135.05))   # CAD hard stops (mean of left and right)
# Thigh shell for the floor contact: convex hull of the CAD thigh group (tools/model/extract_thigh_hull.py).
THIGH_HULL = "model/thigh_hull.json"
HOME_HIP = math.radians(135.05)    # homing pose: hip at its positive stop, knee folded (same as the controller geometry)
KNEE_RANGE = (0.0, math.radians(111.6))
ARMATURE = 1.0e-4                  # reflected rotor inertia, assumed (datasheet has none)
HIP_JOINT_TORQUE = 6.5             # 1.5 N*m hip motor + 5 N*m knee motor through the parallelogram
KNEE_JOINT_TORQUE = 5.0
WHEEL_TORQUE = 0.13
ENVELOPE_PRODUCTS = ("Body 1 v1.3.2-1", "Body 2 v1.3.2", "Robot Head POC")

def load(name: str) -> dict:
    return yaml.safe_load((MODEL / name).read_text(encoding="utf-8"))

def fmt(values, digits=9) -> str:
    return " ".join(f"{float(v):.{digits}g}" for v in values)

def body_part(mass, com, tensor):
    return {"m": mass, "c": np.asarray(com, float), "I": np.asarray(tensor, float)}

def combine(parts):
    """Rigid merge: parts in one frame, inertia tensors about their own COM, axes parallel."""
    mass = sum(p["m"] for p in parts)
    com = sum(p["m"] * p["c"] for p in parts) / mass
    tensor = np.zeros((3, 3))
    for p in parts:
        d = p["c"] - com
        tensor += p["I"] + p["m"] * (np.dot(d, d) * np.eye(3) - np.outer(d, d))
    return {"m": mass, "c": com, "I": tensor}

def cylinder_y(mass, radius, length):
    """Solid cylinder with its axis along y."""
    iy = 0.5 * mass * radius ** 2
    ix = mass * (3 * radius ** 2 + length ** 2) / 12.0
    return np.diag([ix, iy, ix])

def inertial(p) -> str:
    t = p["I"]
    return (f'<inertial pos="{fmt(p["c"])}" mass="{p["m"]:.9g}" '
            f'fullinertia="{fmt([t[0,0], t[1,1], t[2,2], t[0,1], t[0,2], t[1,2]])}"/>')

def link_part(inertials, name):
    row = inertials["links"][name]
    return body_part(row["mass_kg"], row["inertial_pos_link_m"], row["inertia_com_link_kg_m2"])

def build() -> str:
    inertials = load("inertials.yaml")
    frames = {j["name"]: np.asarray(j["origin_body_m"], float) for j in load("joint_frames.yaml")["joints"]}
    actuators = load("actuators.yaml")
    FRICTION = actuators["joint_friction_nm"]            # N*m, defined in actuators.yaml
    TYRE_FRICTION = actuators["contact_friction"]["tyre"]
    BODY_FRICTION = actuators["contact_friction"]["body_shell"]
    imu = load("imu.yaml")["imu"]
    blocks = load("cad_blocks.yaml")["components"]
    stator_m = float(actuators["wheel_assembly"]["motor_mass_kg"])
    spin_m = float(actuators["wheel_assembly"]["mass_kg"]) - stator_m
    stator_r = float(actuators["motors"]["kpower_bl4012"]["dimensions_mm"]["outer_diameter"]) / 2000.0
    stator_h = float(actuators["motors"]["kpower_bl4012"]["dimensions_mm"]["height_without_pcb"]) / 1000.0

    # Body = body_link + head carried at its yaw-joint origin.
    head = link_part(inertials, "head")
    head["c"] = head["c"] + frames["head_yaw"]
    body = combine([link_part(inertials, "body_link"), head])

    hull = json.loads((ROOT / THIGH_HULL).read_text(encoding="utf-8"))
    lines = [
        "<!-- Generated by tools/model/generate_dynamic_model.py from the RB v1.3 YAML files. Do not edit by hand. -->",
        '<mujoco model="rb_v1_3_dynamic">',
        '  <compiler angle="radian" autolimits="true"/>',
        '  <option timestep="0.0005" gravity="0 0 -9.81" integrator="implicitfast" cone="elliptic"/>',
        '  <default>',
        f'    <joint damping="0" armature="{ARMATURE:g}"/>',
        '    <geom contype="0" conaffinity="0" solref="0.006 1" solimp="0.95 0.99 0.001"/>',   # contacts only through the <pair> list
        '  </default>',
        '  <asset>',
        *[f'    <mesh name="{side}_thigh_hull" vertex="{" ".join(f"{v:.4f}" for p in hull[side]["vertices_m"] for v in p)}"/>'
          for side in ("left", "right")],
        '  </asset>',
        '  <worldbody>',
        '    <light name="key" pos="0 -1 1.5" dir="0 1 -1"/>',
        '    <geom name="ground" type="plane" pos="0 0 0" size="2 2 0.1" rgba="0.20 0.22 0.24 1"/>',
    ]
    spawn_z = 0.0
    legs = []
    for side, sign in (("left", 1.0), ("right", -1.0)):
        hip = frames[f"{side}_hip"]
        knee = frames[f"{side}_knee"] - hip
        wheel = frames[f"{side}_wheel"] - frames[f"{side}_knee"]
        thigh = link_part(inertials, f"{side}_thigh")
        shin_link = link_part(inertials, f"{side}_shin")
        stator = body_part(stator_m, wheel, cylinder_y(stator_m, stator_r, stator_h))
        shin = combine([shin_link, stator])
        wheel_part = body_part(spin_m, [0.0, 0.0, 0.0], cylinder_y(spin_m, WHEEL_RADIUS, 2 * WHEEL_HALF_WIDTH))
        legs.append((side, hip, knee, wheel, thigh, shin, wheel_part))
        spawn_z = max(spawn_z, -(knee[2] + wheel[2]))     # neutral-pose axle depth below the hip

    lines += [
        f'    <body name="body_link" pos="0 0 {spawn_z + WHEEL_RADIUS:.9g}">',
        '      <freejoint name="root"/>',
        f'      {inertial(body)}',
    ]
    box_bounds = []
    box_names = []
    for product in ENVELOPE_PRODUCTS:
        row = next(c for c in blocks if c["product"] == product and len(c["assembly_path"]) == 1)
        lo, hi = np.asarray(row["aabb_min_body_m"]), np.asarray(row["aabb_max_body_m"])
        box_bounds.append((lo, hi))
        box_names.append(f"{product.split()[0].lower()}_{product.split()[1].lower()}")
        lines.append(f'      <geom name="{box_names[-1]}" type="box" '
                     f'pos="{fmt((lo + hi) / 2)}" size="{fmt((hi - lo) / 2)}" rgba="0.7 0.7 0.72 1"/>')
    pos = imu["position_body_m"]
    lines.append(f'      <site name="imu" pos="{fmt(pos)}" size="0.004"/>')
    for side, hip, knee, wheel, thigh, shin, wheel_part in legs:
        sign = 1.0 if side == "left" else -1.0
        lines += [
            f'      <body name="{side}_thigh" pos="{fmt(hip)}">',
            f'        <joint name="{side}_hip" type="hinge" axis="0 1 0" range="{fmt(HIP_RANGE)}" limited="true" '
            f'frictionloss="{FRICTION["hip"]}"/>',
            f'        {inertial(thigh)}',
            f'        <geom name="{side}_thigh_hull" type="mesh" mesh="{side}_thigh_hull" rgba="0.4 0.6 0.5 1"/>',
            f'        <body name="{side}_shin" pos="{fmt(knee)}">',
            f'          <joint name="{side}_knee" type="hinge" axis="0 1 0" range="{fmt(KNEE_RANGE)}" limited="true" '
            f'frictionloss="{FRICTION["knee"]}"/>',
            f'          {inertial(shin)}',
            f'          <body name="{side}_wheel" pos="{fmt(wheel)}">',
            f'            <joint name="{side}_wheel" type="hinge" axis="0 1 0" frictionloss="{FRICTION["wheel"]}"/>',
            f'            {inertial(wheel_part)}',
            f'            <geom name="{side}_wheel_collision" type="cylinder" size="{WHEEL_RADIUS} {WHEEL_HALF_WIDTH}" '
            f'quat="0.7071067812 0.7071067812 0 0" rgba="0.08 0.09 0.10 1"/>',
            '          </body>', '        </body>', '      </body>']
    lines += ['    </body>', '  </worldbody>', '  <contact>']
    for side in ("left", "right"):
        lines.append(f'    <pair geom1="ground" geom2="{side}_wheel_collision" condim="3" '
                     f'friction="{TYRE_FRICTION:g} {TYRE_FRICTION:g} 0 0 0" solref="0.006 1" solimp="0.95 0.99 0.001"/>')
    for name in box_names + [f"{side}_{part}" for side in ("left", "right") for part in ("thigh_hull",)]:
        lines.append(f'    <pair geom1="ground" geom2="{name}" condim="3" '
                     f'friction="{BODY_FRICTION:g} {BODY_FRICTION:g} 0.001 0 0" solref="0.006 1" solimp="0.95 0.99 0.001"/>')
    lines += ['  </contact>', '  <actuator>']
    for side in ("left", "right"):
        lines.append(f'    <motor name="{side}_hip_torque" joint="{side}_hip" ctrllimited="true" '
                     f'ctrlrange="{-HIP_JOINT_TORQUE} {HIP_JOINT_TORQUE}"/>')
        lines.append(f'    <motor name="{side}_knee_torque" joint="{side}_knee" ctrllimited="true" '
                     f'ctrlrange="{-KNEE_JOINT_TORQUE} {KNEE_JOINT_TORQUE}"/>')
    for side in ("left", "right"):
        lines.append(f'    <motor name="{side}_wheel_torque" joint="{side}_wheel" ctrllimited="true" '
                     f'ctrlrange="{-WHEEL_TORQUE} {WHEEL_TORQUE}"/>')
    lines += ['  </actuator>', '  <sensor>',
              '    <accelerometer name="imu_accel" site="imu"/>', '    <gyro name="imu_gyro" site="imu"/>']
    for side in ("left", "right"):
        for joint in ("hip", "knee", "wheel"):
            lines.append(f'    <jointpos name="enc_{side}_{joint}_pos" joint="{side}_{joint}"/>'
                         f'<jointvel name="enc_{side}_{joint}_vel" joint="{side}_{joint}"/>')
    # Keyframes: straight legs (knee at the 110 degree soft limit, axle under the hip) and the CAD pose.
    knee_up = math.radians(110.0)
    k = (legs[0][2] + legs[1][2]) / 2
    w = (legs[0][3] + legs[1][3]) / 2
    def axle(hip_angle):
        c, s = math.cos(hip_angle), math.sin(hip_angle)
        up = np.array([c * k[0] + s * k[2], -s * k[0] + c * k[2]])
        c2, s2 = math.cos(hip_angle + knee_up), math.sin(hip_angle + knee_up)
        return up + np.array([c2 * w[0] + s2 * w[2], -s2 * w[0] + c2 * w[2]])
    lo_h, hi_h = -2.0, 0.0
    for _ in range(80):
        mid = (lo_h + hi_h) / 2
        lo_h, hi_h = (mid, hi_h) if axle(mid)[0] > 0 else (lo_h, mid)
    hip_straight = (lo_h + hi_h) / 2
    straight_z = -axle(hip_straight)[1] + WHEEL_RADIUS
    joints = lambda h, kn: f"{h:.9g} {kn:.9g} 0 {h:.9g} {kn:.9g} 0"
    home_z = -min(b[0][2] for b in box_bounds) + 0.0005   # body resting on its lowest shell face
    lines += ['  </sensor>', '  <keyframe>',
              f'    <key name="spawn_extended" qpos="0 0 {straight_z:.9g} 1 0 0 0 {joints(hip_straight, knee_up)}"/>',
              f'    <key name="home" qpos="0 0 {home_z:.9g} 1 0 0 0 {joints(HOME_HIP, 0)}"/>',
              f'    <key name="cad_neutral" qpos="0 0 {spawn_z + WHEEL_RADIUS:.9g} 1 0 0 0 {joints(0, 0)}"/>',
              '  </keyframe>', '</mujoco>', '']
    return "\n".join(lines)

def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build(), encoding="utf-8")
    print(f"wrote {args.out}")

if __name__ == "__main__":
    main()
